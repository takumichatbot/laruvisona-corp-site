/**
 * サイトカードの「見た目」。
 *
 * いまは屋号の頭文字を大きく置くだけ。中身は分からない。
 *
 * ── なぜ、実物を出すのをやめたか（2026-09-17） ───────────────
 *
 * 「完成像を見ながら作る」と売っているのに管理画面でその完成像が見えないのは
 * 惜しいので、カードの中に実物を出そうとした。
 * `GET /api/sites/<id>/export-html?inline=1` が下書きからHTMLを作って返すので、
 * それを sandbox="" の iframe に読ませる、という作りにした。
 *
 * 動かなかった。本番で7枚すべてが**白いまま**だった。しかも、
 *   ・枠は読み込み済み（onLoad は発火する）
 *   ・位置も大きさも正しい
 *   ・返ってくるHTMLも正しい（62KB・本文41,000字）
 *   ・その枠を手で1px動かすと、その場で絵が出る
 * つまり **コードからは、どこも壊れていないように見える。**
 *
 * 3回出荷して、3回とも本番で白かった。
 *   1回目 透明から見せる作りをやめた → 白いまま
 *   2回目 縮小をやめ、読み込み後に描き直させた → 白いまま
 *   3回目 カードと同じ大きさにした → 白いまま
 *
 * 白い四角は、頭文字の面より**悪い**。頭文字は「そういう見た目」に見えるが、
 * 白い四角は壊れて見える。だから戻した。
 *
 * ── 次にやるなら ─────────────────────────────────
 *
 * ブラウザに描かせて縮めるのではなく、**サーバー側で1枚の絵にする**こと。
 * 公開・更新のときに1回だけ描いて保存し、カードはその絵を出すだけにする。
 * 描くのが1回で済むので速く、描けたかどうかもその場で分かる。
 * 出す口（export-html?inline=1）はそのまま残してあるので、材料は揃っている。
 */

export default function SiteThumb({
  name, gradient,
}: {
  name: string;
  /** カードごとに色を変える、これまでの見た目 */
  gradient: string;
}) {
  return (
    <div className="site-thumb">
      <div className={`site-thumb-fallback bg-gradient-to-br ${gradient}`}>
        <span className="site-thumb-initial">{(name || '?').charAt(0).toUpperCase()}</span>
      </div>
    </div>
  );
}
