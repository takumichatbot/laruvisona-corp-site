/**
 * 業種ページの中身。
 *
 * ここを作った理由。
 * 以前この15ページは、業種名と1段落だけを差し替えた同じ型紙だった。
 * 本番で機械的に比べたところ、互いに平均76%一致し、業種ごとに違うのは
 * 57行中11行——実質150字ほどしかなかった。検索側から見れば、同じページを
 * 15枚並べているのと変わらない。市区町村ページを量産しないと決めたのと
 * 同じ理由で、これも抱えているだけ損になる。
 *
 * そこで、その業種の人にしか書けないことだけを足した。
 *   problems … その業種でよく起きる困りごと
 *   musts    … 載せる情報と、載せる「理由」
 *   inquiry  … 問い合わせや予約が実際どう来るか
 *   rules    … 公開前に自分で確かめる決まりごと
 *   faq      … その業種の人が実際に聞くこと
 *
 * rules は法令の助言ではない。「この決まりがあるので、自分の内容を
 * 確かめてください」という確認項目である。判断は事業者と、必要なら
 * その分野の専門家が行う。画面にもそう書いてある。
 */

